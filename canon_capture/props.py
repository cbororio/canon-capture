def exposure_comp(value):
    v = value & 0xFF
    if v > 0x7F:
        v -= 0x100
    if v == 0:
        return "0"
    sign = "+" if v > 0 else "−"
    whole, frac = divmod(abs(v), 8)
    frac_text = {3: "1/3", 4: "1/2", 5: "2/3"}.get(frac, "")
    if whole and frac_text:
        return f"{sign}{whole} {frac_text}"
    return f"{sign}{whole or frac_text}"


def label(table, value):
    if callable(table):
        return table(value)
    return table.get(value, f"0x{value:X}")
